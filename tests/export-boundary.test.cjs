const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const ctx=vm.createContext({console,Date,Blob,TextEncoder,Uint8Array,DataView});
const load=file=>vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),ctx,{filename:file});
load('src/core/export-layout.js');
load('src/adapters/export-files.js');
load('src/outputs/canvas.js');
const {Zhou}=ctx;
const model={version:1,updated:'2026-10-15',from:400,to:300,cursor:350,category:'战争',stateNames:{a:'甲',b:'乙'},states:[{id:'a',name:'甲',start:500,end:221,color:'#123456',interruptions:[],rulers:[{id:'r1',name:'甲君',start:450,end:350,source:'https://example.com/ruler',dating:{level:'certain'}}]}],events:[{id:'e1',year:375,name:'甲乙之战',states:['a','b'],kind:'战争',description:'事件说明',sources:[{title:'事件来源',url:'https://example.com/event'}]}],sources:[]};
const before=JSON.stringify(model);
const measured=[];
const plan=Zhou.buildExportPlan(model,{span:100,cursor:350,category:'战争'},(text,size,bold)=>{measured.push({size,bold});return text.length*size;});
assert.equal(JSON.stringify(model),before,'layout must not mutate its comparison snapshot');
assert.equal(plan.updated,model.updated);
assert.equal(plan.events[0].e,model.events[0]);
assert.equal(plan.states[0],model.states[0]);
assert.equal(plan.pages.filter(p=>p.type==='chart').length,2);
assert(plan.pages.filter(p=>p.type==='index').flatMap(p=>p.lines).some(line=>line.text.includes('甲、乙')));
assert(plan.sources.some(s=>s.url==='https://example.com/ruler'));
assert(plan.sources.some(s=>s.url==='https://example.com/event'));
assert(measured.some(m=>m.bold));
assert.throws(()=>Zhou.buildExportPlan({...model,from:200}, {},()=>1),/有效范围/);
assert.throws(()=>Zhou.buildExportPlan({...model,states:[]}, {},()=>1),/没有显示的国家/);
const packed=Zhou.exportRulerLanes({rulers:[{name:'甲',start:400,end:350},{name:'乙',start:350,end:300}]},400,300);
assert.equal(packed.lanes,2,'same-year succession must retain separate lanes');
// Render before defining any browser UI globals: the output module must stand alone.
const drawn=[],rects=[];
const fakeCanvas={measureText:text=>({width:text.length*14}),fillText:(text,x,y)=>drawn.push({text,x,y}),fillRect:(...args)=>rects.push(args),beginPath(){},moveTo(){},lineTo(){},closePath(){},stroke(){},fill(){},strokeRect(){},setLineDash(){}};
const planBeforeRender=JSON.stringify(plan);
plan.pages.forEach((page,index)=>Zhou.drawExportPage(fakeCanvas,page,plan,index));
assert.equal(JSON.stringify(plan),planBeforeRender,'canvas output must not mutate the plan');
assert(drawn.some(line=>line.text==='E1'),'chart event markers retain index numbering');
assert(drawn.some(line=>line.text==='甲君'),'ruler bars retain their labels when space permits');
assert(drawn.some(line=>line.text.includes('甲乙之战')),'index text is rendered');
assert(drawn.some(line=>line.text.includes('资料更新 2026-10-15')),'footer reads metadata from the plan');
assert(rects.some(args=>args[0]===0&&args[1]===0&&args[2]===1200&&args[3]===850));
// The browser wrapper delegates selection exactly once and passes the snapshot into layout.
const elements=new Map();ctx.$=selector=>{if(!elements.has(selector))elements.set(selector,{});return elements.get(selector);};
ctx.window={addEventListener(){}};
let comparisonCalls=0;
ctx.historyService={comparison(options){comparisonCalls++;assert.deepEqual(options.states,['a']);return model;}};
load('src/export.js');
const wrapped=ctx.buildExportPlan({states:['a'],span:100,cursor:350,category:'战争'},{measureText:text=>({width:text.length*18})});
assert.equal(comparisonCalls,1);
assert.equal(wrapped.events[0].e.id,'e1');
ctx.drawExportPage(fakeCanvas,wrapped.pages[0],wrapped,0);
(async()=>{
 assert.equal(Zhou.exportCRC32(new TextEncoder().encode('123456789')),0xcbf43926);
 const zip=new Uint8Array(await Zhou.buildImagesZIP([new Uint8Array([1,2,3])]).arrayBuffer());
 const view=new DataView(zip.buffer);
 assert.equal(view.getUint32(0,true),0x04034b50);
 assert.equal(view.getUint32(zip.length-22,true),0x06054b50);
 assert.equal(view.getUint16(zip.length-14,true),1);
 const pdf=await Zhou.buildImagePDF([new Uint8Array([255,216,255,217])]).text();
 assert(pdf.startsWith('%PDF-1.4\n'));
 const xref=Number(pdf.match(/startxref\n(\d+)/)[1]);
 assert.equal(pdf.slice(xref,xref+4),'xref');
 assert(pdf.includes('/Count 1'));
 console.log('PASS export boundary: snapshot-only pagination, browser delegation, immutable content, standalone canvas rendering, PDF and ZIP encoders.');
})().catch(error=>{console.error(error);process.exit(1);});
