import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {catalog,compileProduction} from './lib/production.mjs';

const read = path => readFileSync(new URL(path, import.meta.url), 'utf8');
const hash = content => createHash('sha256').update(content).digest('hex');
const bundles = {
  'app.js': ['src/core/time.js', 'src/core/history.js', 'src/core/search.js', 'src/core/state.js', 'src/core/combinations.js', 'src/core/navigation.js', 'src/core/reading.js', 'src/core/view-link.js', 'src/adapters/storage.js', 'src/adapters/timeline-dom.js', 'src/ui/view.js', 'src/app.js', 'src/ui/search-details.js', 'src/ui/timeline.js', 'src/ui/navigation-details.js', 'src/ui/controls.js', 'src/startup.js'],
  'study.js': ['src/study.js'],
  'share.js': ['src/share.js'],
  'export.js': ['src/core/export-layout.js', 'src/outputs/canvas.js', 'src/adapters/export-files.js', 'src/export.js']
};
const outputs = new Map(), datasets=[];
for(const topic of catalog){
  const source=read('./data/'+topic.file), data=compileProduction(JSON.parse(source),topic.id);
  const asset=topic.id==='zhou'?'data.js':'data-'+topic.id+'.js';
  outputs.set(asset,'window.ZHOU_DATA = '+JSON.stringify(data)+';\n');
  datasets.push({...topic,asset,sourceSha256:hash(source),counts:Object.fromEntries(['polities','people','tenures','events','activities'].map(k=>[k,data[k].length]))});
}
for (const [name, paths] of Object.entries(bundles)) outputs.set(name, '// Generated by build.mjs. Edit src/ instead.\n' + paths.map(path => `// ---- ${path} ----\n${read('./' + path).trim()}\n`).join('\n'));
outputs.set('style.css', read('./src/style.css'));
// Every page and its assets use one deterministic release; file:// remains usable.
for(const topic of datasets){
  let template=read('./src/index.html').replace('src="data.js"',`src="${topic.asset}"`);
  if(topic.id!=='zhou')template=template.replace('<title>周代列国 · 历史对照图</title>',`<title>${topic.name} · 历史对照图</title>`).replace('在共同年代轴上，对照周王室与17个主要诸侯国的君主更替、重大事件和兴亡。',`${topic.name}正式资料：在共同年代轴上对照政权、任期、人物与重大事件。`);
  const html=template.replace(/((?:src|href)=")([^"/?]+\.(?:js|css))"/g, (match, prefix, name) => {
    const asset = outputs.get(name);
    if (asset === undefined) throw new Error(`页面引用了未生成的文件：${name}`);
    return `${prefix}${name}?v=${hash(asset).slice(0,12)}"`;
  });
  outputs.set(topic.page,html);
}
const assets=Object.fromEntries([...outputs].map(([name,content])=>[name,hash(content)]));
outputs.set('release.json',JSON.stringify({releaseId:hash(JSON.stringify(assets)),datasets,assets},null,2)+'\n');
const check = process.argv.includes('--check');
if (!check) mkdirSync(new URL('./dist/', import.meta.url), {recursive: true});
for (const [name, content] of outputs) {
  const output = new URL('./dist/' + name, import.meta.url);
  if (check) {
    let actual;
    try { actual = readFileSync(output, 'utf8'); } catch {}
    if (actual !== content) throw new Error(`dist/${name} 缺失或已过期，请运行 node build.mjs`);
  } else writeFileSync(output, content);
}
console.log(check ? '资料与所有发布文件一致。' : '已生成三时期离线可用的 dist 发布目录。');
