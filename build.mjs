import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {serializeAtlas} from './lib/atlas.mjs';

const read = path => readFileSync(new URL(path, import.meta.url), 'utf8');
const bundles = {
  'app.js': ['src/core/history.js', 'src/core/search.js', 'src/core/state.js', 'src/core/navigation.js', 'src/core/reading.js', 'src/core/view-link.js', 'src/adapters/storage.js', 'src/adapters/timeline-dom.js', 'src/app.js', 'src/ui/search-details.js', 'src/ui/timeline.js', 'src/ui/navigation-details.js', 'src/ui/controls.js'],
  'study.js': ['src/study.js'],
  'share.js': ['src/share.js'],
  'export.js': ['src/core/export-layout.js', 'src/outputs/canvas.js', 'src/adapters/export-files.js', 'src/export.js']
};
const outputs = new Map([['data.js', serializeAtlas(JSON.parse(read('./data/atlas.json')))]]);
for (const [name, paths] of Object.entries(bundles)) outputs.set(name, '// Generated by build.mjs. Edit src/ instead.\n' + paths.map(path => `// ---- ${path} ----\n${read('./' + path).trim()}\n`).join('\n'));
for (const name of ['index.html', 'style.css']) outputs.set(name, read('./src/' + name));
const check = process.argv.includes('--check');
if (!check) mkdirSync(new URL('./dist/', import.meta.url), {recursive: true});
for (const [name, content] of outputs) {
  const output = new URL('./dist/' + name, import.meta.url);
  if (check) {
    let actual;
    try { actual = readFileSync(output, 'utf8'); } catch {}
    if (actual !== content) throw new Error(`dist/${name} 缺失或已过期，请运行 node build.mjs`);
  } else writeFileSync(output, content);
}
console.log(check ? '资料与所有发布文件一致。' : '已生成离线可用的 dist 发布目录。');
